import assert from 'node:assert/strict'
import test from 'node:test'
import { 归纳多篇章语义分布, 提取篇章独特概念, 语义学透镜, 语义篇章 } from '../src/index.js'

void test('语义学透镜应能提取核心概念、共现邻域与语义转折点', () => {
  let 透镜 = new 语义学透镜()
  let 文章 = [
    '记忆系统需要长期沉淀用户的真实偏好，而不是机械记录流水账。',
    '当记忆系统积累了足够多的上下文样本，智能体就能在对话中保持连贯的认知。',
    '保持认知连贯的前提，是把零散记忆结构化为可检索的概念网络。',
    '今天中午楼下咖啡馆新出了一款冰美式，酸度偏高但香气很足。',
  ].join('\n')

  let 篇章 = 透镜.同步剖析文章({ 文本: 文章, 来源标签: '测试文章' })

  assert.equal(篇章.获得单元数量(), 4)

  let 核心概念 = 篇章.获取核心概念(5)
  assert.ok(核心概念.length > 0)
  assert.ok(核心概念.some((项) => 项.词 === '记忆' || 项.词 === '系统' || 项.词 === '连贯'))

  let 邻域 = 篇章.获得概念共现图().查询关联概念('记忆')
  assert.ok(邻域.length > 0)

  let 概念簇们 = 篇章.获得概念共现图().识别概念簇(2)
  assert.ok(概念簇们.length >= 2)

  let 转折点列表 = 篇章.定位语义转折点(0.05)
  assert.ok(转折点列表.some((点) => 点.后单元原文.includes('冰美式')))
})

void test('应能通过无状态函数计算跨篇章 TF-IDF 独特概念与多篇章分布摘要并支持快照恢复', () => {
  let 透镜 = new 语义学透镜()

  let 篇章甲 = 透镜.同步剖析文章({
    文本: '人格心理学关注防御姿态与权力位阶。对话中的情绪张力往往决定了表达方式。',
    来源标签: '心理学',
  })
  let 篇章乙 = 透镜.同步剖析文章({
    文本: '分布式数据库关注一致性协议与 Raft 日志复制。节点故障时需要快速完成选主。',
    来源标签: '系统架构',
  })

  assert.ok(篇章甲.对比另一篇章(篇章乙) < 0.2)

  let 篇章列表 = [篇章甲, 篇章乙]
  let 甲独特概念 = 提取篇章独特概念(篇章甲, 篇章列表, 5)
  assert.ok(甲独特概念.some((项) => 项.词 === '心理学' || 项.词 === '人格' || 项.词 === '情绪'))

  let 分布摘要 = 归纳多篇章语义分布(篇章列表)
  assert.equal(分布摘要.篇章总数, 2)
  assert.ok(分布摘要.高频概念们.length > 0)

  let 恢复篇章乙 = new 语义篇章(篇章乙.导出快照())
  assert.equal(恢复篇章乙.获得来源标签(), '系统架构')
  assert.equal(恢复篇章乙.获得单元数量(), 篇章乙.获得单元数量())
})

void test('语义学透镜应支持注入异步向量化函数计算余弦语义连贯度', async () => {
  let 模拟向量表: Record<string, number[]> = {
    '第一句探讨认知模型与推理机制。': [1, 0, 0],
    '第二句继续深入推理机制的边界。': [0.95, 0.05, 0],
    '第三句突然切换去讨论周末买菜。': [0, 0, 1],
  }

  let 透镜 = new 语义学透镜({
    向量化函数: async (文本列表: string[]): Promise<number[][]> =>
      文本列表.map((文本) => 模拟向量表[文本] ?? [0, 1, 0]),
  })

  let 篇章 = await 透镜.剖析文章({ 文本: Object.keys(模拟向量表).join('\n') })

  let 曲线 = 篇章.计算相邻连贯度曲线()
  assert.equal(曲线.length, 2)
  assert.ok((曲线[0] ?? 0) > 0.9)
  assert.equal(曲线[1], 0)

  let 转折点 = 篇章.定位语义转折点(0.2)
  assert.equal(转折点.length, 1)
  assert.equal(转折点[0]?.单元位置, 2)
})
