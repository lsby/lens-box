import { 语义学透镜 } from '../src/index.js'

function 运行语义剖析演示(): void {
  let 透镜 = new 语义学透镜()

  let 文章甲 = [
    '记忆系统不是冰冷的数据库，而是随时间不断重构的主观叙事。',
    '当我们回溯一段旧记忆时，当下的情绪基调会悄悄改写记忆的权重与细节。',
    '因此，真正拟人化的记忆架构必须允许遗忘、联想与概念共现的动态演化。',
    '顺便一提，今天晚上的番茄炒蛋好像放多了一点糖，但意外地很下饭。',
  ].join('\n')

  let 文章乙 = [
    '构建多视角认知工具箱的核心，是放弃包罗万象的单一超级模型。',
    '心理学视角关注人物性格与防御姿态，而语义学视角关注概念网络与篇章连贯度。',
    '当多个独立视角并存时，系统就能在具体语境下自由组合出更丰富的理解。',
  ].join('\n')

  let 篇章甲 = 透镜.同步剖析文章({ 文本: 文章甲, 来源标签: '记忆随笔' })
  let 篇章乙 = 透镜.同步剖析文章({ 文本: 文章乙, 来源标签: '架构思考' })

  console.log('=== 文章甲：核心概念 Top 8 ===')
  console.log(篇章甲.获取核心概念(8))

  console.log('\n=== 文章甲：“记忆”的共现语义邻域 ===')
  console.log(篇章甲.获得概念共现图().查询关联概念('记忆', 6))

  console.log('\n=== 文章甲：概念簇 ===')
  console.log(篇章甲.获得概念共现图().识别概念簇(2))

  console.log('\n=== 文章甲：相邻连贯度曲线与指标 ===')
  console.log({
    平均信息密度: Number(篇章甲.评估平均信息密度().toFixed(4)),
    平均连贯度: Number(篇章甲.评估平均连贯度().toFixed(4)),
    主题收敛度: Number(篇章甲.评估主题收敛度().toFixed(4)),
    相邻连贯度曲线: 篇章甲.计算相邻连贯度曲线().map((值) => Number(值.toFixed(4))),
  })

  console.log('\n=== 文章甲：语义转折点 ===')
  console.log(篇章甲.定位语义转折点(0.03))

  console.log('\n=== 跨篇章对比与 TF-IDF 独特概念 ===')
  console.log({
    篇章甲与乙重合度: Number(篇章甲.对比另一篇章(篇章乙).toFixed(4)),
    篇章甲独特概念: 透镜.获得档案().提取篇章独特概念(篇章甲.获得篇章标识(), 5),
    篇章乙独特概念: 透镜.获得档案().提取篇章独特概念(篇章乙.获得篇章标识(), 5),
    档案分布摘要: 透镜.获得档案().归纳档案分布(),
  })
}

运行语义剖析演示()
