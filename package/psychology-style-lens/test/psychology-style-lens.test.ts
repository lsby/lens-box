import assert from 'node:assert/strict'
import test from 'node:test'
import OpenAI from 'openai'
import { 心理学文风样本, 心理学文风透镜, 心理学样本档案 } from '../src/index.js'

void test('心理学文风样本与档案应支持收录、防重、多维检索、分布归纳与快照恢复', () => {
  let 样本甲 = new 心理学文风样本({
    样本标识: 'sample-1',
    原文: '就这点本事也敢出来丢人现眼？真拿你没办法呀～',
    人物性格: {
      主导特质: ['嘴硬心软', '骄傲'],
      情绪基调: '调侃中带着轻微嫌弃',
      表达动机: '在保持高姿态的同时准备出手帮忙',
      防御或互动姿态: '玩笑式打压',
    },
    对话场景: { 场景类型: '熟人间的日常拌嘴', 社交距离: '熟络', 权力位阶: '平级', 气氛张力: '表面挑衅但实则亲近' },
    记录时间戳: 1700000000000,
    来源标签: '角色台词',
  })

  let 样本乙 = new 心理学文风样本({
    样本标识: 'sample-2',
    原文: '请把第三季度的财务报表在五点前放到我桌上。',
    人物性格: {
      主导特质: ['冷静', '克制'],
      情绪基调: '公事公办',
      表达动机: '下达明确的工作指令',
      防御或互动姿态: '保持职业边界',
    },
    对话场景: { 场景类型: '上下级工作安排', 社交距离: '礼貌', 权力位阶: '上位', 气氛张力: '严肃且克制' },
    记录时间戳: 1700000001000,
    来源标签: '职场对话',
  })

  let 档案 = new 心理学样本档案([样本甲])
  档案.收录(样本乙)
  assert.equal(档案.获得样本数量(), 2)

  assert.throws(() => {
    档案.收录(样本甲)
  }, /重复收录/)

  let 性格命中 = 档案.按性格检索('嘴硬')
  assert.equal(性格命中.length, 1)
  assert.equal(性格命中[0]?.获得样本标识(), 'sample-1')

  let 场景命中 = 档案.按场景检索({ 社交距离: '礼貌', 权力位阶: '上位' })
  assert.equal(场景命中.length, 1)
  assert.equal(场景命中[0]?.获得样本标识(), 'sample-2')

  let 分布 = 档案.归纳画像分布()
  assert.equal(分布.样本总数, 2)
  assert.equal(分布.社交距离分布['熟络'], 1)
  assert.equal(分布.权力位阶分布['上位'], 1)

  let 恢复档案 = 心理学样本档案.从快照Json恢复(档案.导出快照Json())
  assert.equal(恢复档案.获得样本数量(), 2)
  assert.equal(恢复档案.按条件检索({ 来源标签: '角色台词' }).length, 1)
})

void test('心理学文风透镜应能构建观察命令并拒绝空输入', () => {
  let 占位客户端 = new OpenAI({ apiKey: 'unused-for-offline-test' })
  let 透镜 = new 心理学文风透镜({ openai客户端: 占位客户端, 模型名称: 'unused-model' })

  let 命令 = 透镜.构建心理学观察命令({
    文本: '你该不会连这个都要我教吧？',
    上下文提示: '两人刚认识不久，对方在试探底线',
  })

  assert.ok(命令.includes('补充上下文：两人刚认识不久，对方在试探底线'))
  assert.ok(命令.includes('你该不会连这个都要我教吧？'))

  assert.throws(() => {
    透镜.构建心理学观察命令({ 文本: '   ' })
  }, /不能为空/)
})
