function 生成节拍音符(序列: Array<[string, number]>, 起始时间 = 0): 音符输入[] {
  let 当前 = 起始时间
  let 结果: 音符输入[] = []
  for (let [音名, 拍数] of 序列) {
    let 时长 = 拍数 * 0.5
    结果.push({ 音名, 按下时间: 当前, 弹起时间: 当前 + 时长 * 0.92 })
    当前 += 时长
  }
  return 结果
}

