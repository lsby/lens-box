import { 音符 } from '../model/note.js'
import { 重音处理策略 } from '../schema.js'

/**
 * LBDM 乐句切分配置参数。
 */
export type 乐句切分配置 = {
  边界阈值?: number
  最小乐句音符数?: number
  音高权重?: number
  间隔权重?: number
  休止权重?: number
}

/**
 * 将音符序列按按下时间排序，并在需要时执行 Skyline 主旋律抽取（同时发声时保留最高音）。
 */
export function 规范化音轨音符(原始音符列表: readonly 音符[], 策略: 重音处理策略): 音符[] {
  let 已排序 = [...原始音符列表].sort((甲, 乙) => {
    let 时间差 = 甲.获得按下时间() - 乙.获得按下时间()
    if (Math.abs(时间差) > 1e-6) {
      return 时间差
    }
    return 乙.获得音高().获得半音编号() - 甲.获得音高().获得半音编号()
  })

  if (策略 === '保留全部') {
    return 已排序
  }

  let 结果: 音符[] = []
  let 同拍容差 = 0.03

  for (let 当前音 of 已排序) {
    let 上一音 = 结果[结果.length - 1]
    if (上一音 === undefined) {
      结果.push(当前音)
      continue
    }

    if (Math.abs(当前音.获得按下时间() - 上一音.获得按下时间()) <= 同拍容差) {
      if (当前音.获得音高().获得半音编号() > 上一音.获得音高().获得半音编号()) {
        结果[结果.length - 1] = 当前音
      }
      continue
    }

    if (当前音.获得按下时间() < 上一音.获得弹起时间() - 1e-6) {
      // 若前一个音尚未结束就被更高或后续主旋律音切入，截断前音尾部以保持单声部连续性
      if (当前音.获得按下时间() > 上一音.获得按下时间() + 1e-6) {
        结果[结果.length - 1] = new 音符(上一音.获得音高(), 上一音.获得按下时间(), 当前音.获得按下时间())
      }
    }
    结果.push(当前音)
  }

  return 结果
}

function 计算局部变化率(序列: readonly number[]): number[] {
  let 长度 = 序列.length
  if (长度 < 2) {
    return 序列.map(() => 0)
  }
  let 变化率列表: number[] = []
  for (let 索引 = 0; 索引 < 长度 - 1; 索引 += 1) {
    let 当前 = 序列[索引] ?? 0
    let 下一个 = 序列[索引 + 1] ?? 0
    let 分母 = 当前 + 下一个
    if (分母 <= 1e-9) {
      变化率列表.push(0)
    } else {
      变化率列表.push(Math.abs(下一个 - 当前) / 分母)
    }
  }
  return 变化率列表
}

function 计算单维边界强度(序列: readonly number[]): number[] {
  let 长度 = 序列.length
  if (长度 === 0) {
    return []
  }
  let 变化率 = 计算局部变化率(序列)
  let 原始强度: number[] = []
  let 最大值 = 0

  for (let 索引 = 0; 索引 < 长度; 索引 += 1) {
    let 值 = 序列[索引] ?? 0
    let 左变化 = 索引 > 0 ? (变化率[索引 - 1] ?? 0) : 0
    let 右变化 = 索引 < 变化率.length ? (变化率[索引] ?? 0) : 0
    let 强度 = 值 * (左变化 + 右变化)
    原始强度.push(强度)
    if (强度 > 最大值) {
      最大值 = 强度
    }
  }

  if (最大值 <= 1e-9) {
    return 原始强度.map(() => 0)
  }
  return 原始强度.map((强度) => 强度 / 最大值)
}

/**
 * 基于 Cambouropoulos (2001) LBDM 局部边界检测模型切分乐句。
 * 返回切分后的音符二维数组，每个子数组对应一个乐句。
 */
export function 切分乐句序列(音符列表: readonly 音符[], 配置?: 乐句切分配置): 音符[][] {
  if (音符列表.length === 0) {
    return []
  }
  let 最小乐句音符数 = 配置?.最小乐句音符数 ?? 3
  if (音符列表.length < 最小乐句音符数 * 2) {
    return [[...音符列表]]
  }

  let 边界阈值 = 配置?.边界阈值 ?? 0.35
  let 音高权重 = 配置?.音高权重 ?? 0.25
  let 间隔权重 = 配置?.间隔权重 ?? 0.5
  let 休止权重 = 配置?.休止权重 ?? 0.25

  let 音程序列: number[] = []
  let 间隔序列: number[] = []
  let 休止序列: number[] = []

  for (let 索引 = 0; 索引 < 音符列表.length - 1; 索引 += 1) {
    let 当前 = 音符列表[索引]
    let 下一个 = 音符列表[索引 + 1]
    if (当前 === undefined || 下一个 === undefined) {
      continue
    }
    音程序列.push(Math.abs(当前.获得音高().到目标音程(下一个.获得音高())))
    间隔序列.push(当前.到下一音起始间隔(下一个))
    休止序列.push(当前.到下一音休止间隙(下一个))
  }

  let 音高强度 = 计算单维边界强度(音程序列)
  let 间隔强度 = 计算单维边界强度(间隔序列)
  let 休止强度 = 计算单维边界强度(休止序列)

  let 综合边界分: number[] = []
  for (let 索引 = 0; 索引 < 音程序列.length; 索引 += 1) {
    let 分数 = (音高强度[索引] ?? 0) * 音高权重 + (间隔强度[索引] ?? 0) * 间隔权重 + (休止强度[索引] ?? 0) * 休止权重
    综合边界分.push(分数)
  }

  let 候选切分点: Array<{ 切点: number; 分数: number }> = []

  for (let 索引 = 0; 索引 < 综合边界分.length; 索引 += 1) {
    let 当前分 = 综合边界分[索引] ?? 0
    if (当前分 < 边界阈值) {
      continue
    }
    let 左邻分 = 索引 > 0 ? (综合边界分[索引 - 1] ?? 0) : 0
    let 右邻分 = 索引 < 综合边界分.length - 1 ? (综合边界分[索引 + 1] ?? 0) : 0
    let 是否局部峰值 = 当前分 >= 左邻分 && 当前分 >= 右邻分
    if (是否局部峰值 === false) {
      continue
    }

    let 切分后下句起点 = 索引 + 1
    let 剩余长度 = 音符列表.length - 切分后下句起点
    if (切分后下句起点 >= 最小乐句音符数 && 剩余长度 >= 最小乐句音符数) {
      候选切分点.push({ 切点: 切分后下句起点, 分数: 当前分 })
    }
  }

  // 强峰优先的非极大值抑制（NMS）：按边界强度降序落刀，抑制邻近弱波动抢占真句尾
  候选切分点.sort((甲, 乙) => {
    if (Math.abs(乙.分数 - 甲.分数) > 1e-9) {
      return 乙.分数 - 甲.分数
    }
    return 甲.切点 - 乙.切点
  })

  let 切分位置: number[] = []
  for (let 候选 of 候选切分点) {
    let 距离冲突 = 切分位置.some((已选) => Math.abs(已选 - 候选.切点) < 最小乐句音符数)
    if (距离冲突 === false) {
      切分位置.push(候选.切点)
    }
  }
  切分位置.sort((甲, 乙) => 甲 - 乙)

  let 乐句组: 音符[][] = []
  let 起点 = 0
  for (let 切点 of 切分位置) {
    乐句组.push(音符列表.slice(起点, 切点))
    起点 = 切点
  }
  乐句组.push(音符列表.slice(起点))
  return 乐句组
}
